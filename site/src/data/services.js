export const serviceBySlug = (slug) => SERVICES.find((s) => s.slug === slug);

// Цена «от» для карточки услуги: { value, suffix } или null, если цен ещё нет.
// За квартиру важнее, чем за м²: человек ищет «сколько стоит однушка».
export function priceFrom(service) {
  const p = service.price ?? {};
  const nums = (arr) => arr.filter((v) => typeof v === 'number');
  const rooms = nums(Object.values(p.rooms ?? {}));
  if (rooms.length) return { value: Math.min(...rooms), suffix: '' };
  if (typeof p.unit?.price === 'number') return { value: p.unit.price, suffix: ` ${p.unit.label}` };
  if (typeof p.perM2 === 'number') return { value: p.perM2, suffix: ' за м²' };
  return null;
}
